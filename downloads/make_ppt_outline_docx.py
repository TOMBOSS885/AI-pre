# ---------- 辅助函数 ----------
def para(text='', bold=False, size=None, align=None, color=None, space_after=None):
    p = doc.add_paragraph()
    if text:
        r = p.add_run(text)
        r.bold = bold
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = RGBColor(*color)
    if align:
        p.alignment = align
    if space_after is not None:
        p.paragraph_format.space_after = Pt(space_after)
    return p

def field(label, content, label_color=(0x1F, 0x3B, 0x66)):
    """规格卡字段：加粗标签 + 内容。content 为 str 或 list。"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(label + '　')
    r.bold = True
    r.font.name = 'Calibri'
    r.font.color.rgb = RGBColor(*label_color)
    r._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if isinstance(content, list):
        for i, item in enumerate(content):
            r2 = p.add_run(('；' if i else '') + item)
            r2.font.size = Pt(10.5)
    else:
        r2 = p.add_run(content)
        r2.font.size = Pt(10.5)
    return p

def bullets(items):
    for it in items:
        p = doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(it)
        r.font.size = Pt(10.5)

def numbered(items):
    for it in items:
        p = doc.add_paragraph(style='List Number')
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(it)
        r.font.size = Pt(10.5)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        r = hdr[i].paragraphs[0].add_run(h)
        r.bold = True
        r.font.name = 'Calibri'
        r.font.size = Pt(10.5)
        r._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
        shd = hdr[i]._element.get_or_add_tcPr().makeelement(qn('w:shd'), {qn('w:val'): 'clear', qn('w:fill'): 'E8EEF7'})
        hdr[i]._element.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            r = cells[i].paragraphs[0].add_run(v)
            r.font.size = Pt(10.5)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t

